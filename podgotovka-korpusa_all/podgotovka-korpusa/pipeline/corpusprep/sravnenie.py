# -*- coding: utf-8 -*-
"""Сравнение двух документов: одно это или разное, чем отличаются, что новее.

Зачем отдельным умением. За три дня одна и та же задача пришла четырьмя разными
поводами, и каждый раз решалась вручную:

«Новые ставки НДС» — две редакции в разных папках, какая верная;
«Список изменений по учету серийных наборов» — три файла в четырёх папках;
DOC-108 и DOC-130 в методике — один документ под двумя именами;
четыре файла из папки «возможно дубль» — дубли или нет.

Ручной разбор каждый раз давал верный ответ и каждый раз стоил полдня. При этом
именно эта задача названа единственной точкой отказа всего решения: нет пометки
«Неактуально» — в базе две инструкции об одном, обе действующие, и заметить это
нечем.

Что умение отвечает. Три вопроса, по порядку важности:

ОДНО ЛИ ЭТО. Считается по доле дословно общих абзацев, а не по близости
векторов: две редакции одного текста близки по смыслу к любой третьей статье на
ту же тему, а дословное совпадение абзаца подделать нечем.

ЧЕМ ОТЛИЧАЮТСЯ. Абзацы, которые есть только в одном, — списком.

ЧТО НОВЕЕ. По четырём признакам разом, потому что ни один не надёжен
поодиночке: дата в имени файла, дата правки внутри docx, номер редакции Word,
дата файловой системы. Последняя врёт чаще всех — её меняет простое
копирование, — поэтому она считается только при отсутствии остальных.

Отдельно — проверка, которой не было ни у кого: НЕ СТОИТ ЛИ В НАЧАЛЕ ЧУЖОЙ
ЗАГОЛОВОК. Файл «А 2 Передача проекта в работу.docx» внутри оказался
«С Процессы фин.результата и закрытия периода». Дубль мы бы нашли и так, но
взяли бы более поздний по дате — и бот называл бы источником «Передачу проекта»,
отвечая про закрытие периода. Не проходит проверку — документ идёт в очередь к
оператору, а не в базу.
"""
import datetime
import hashlib
import os
import re
import zipfile

# Полосы подобраны по разобранным вручную случаям, а не назначены круглыми
# числами. Что за ними стоит:
#
# 0,97 и выше — «Процесс отгрузки» и «ПечатьСертификатов»: текст совпал
#   дословно, различия только в разметке Word;
# 0,85 — DOC-108 и DOC-130: 1260 общих абзацев из 1438, расходятся коды полей;
# 0,40–0,85 — две редакции одного текста, одна переписана;
# 0,05–0,40 — «Список изменений по учету серийных наборов»: 8 общих абзацев из
#   18, общее начало и разное продолжение. Владелец объяснил: задача была
#   длинной, разработчик выгружал частями;
# ниже 0,05 — разные документы.
POLOSY = [
    (0.97, 'один и тот же документ'),
    (0.85, 'один документ, расходятся мелочи разметки'),
    (0.40, 'две редакции одного текста'),
    (0.05, 'части одной задачи или общий кусок'),
    (0.00, 'разные документы'),
]

DATA_V_IMENI = re.compile(r'(\d{2})[.\-](\d{2})[.\-](\d{2,4})')


def _tekst(put):
    z = zipfile.ZipFile(put)
    try:
        xml = z.read('word/document.xml').decode('utf-8', 'ignore')
        kartinki = {n: hashlib.md5(z.read(n)).hexdigest()
                    for n in z.namelist() if n.startswith('word/media/')}
        try:
            core = z.read('docProps/core.xml').decode('utf-8', 'ignore')
        except KeyError:
            core = ''
    finally:
        z.close()
    return re.sub(r'<[^>]+>', ' ', re.sub(r'</w:p>', '\n', xml)), kartinki, core


def _abzacy(tekst, minimum=40):
    """Абзацы длиннее minimum, с схлопнутыми пробелами.

    Схлопывание обязательно: Word рассыпает по абзацу неразрывные пробелы и
    переносы в разных местах у разных копий, и сравнение «как есть» показывает
    различия там, где текст один и тот же. На «Списке изменений» это давало
    десять ложных расхождений из восемнадцати абзацев.
    """
    out = []
    for s in tekst.split('\n'):
        s = re.sub(r'\s+', ' ', s).strip()
        if len(s) > minimum:
            out.append(s)
    return out


def _daty(put, core):
    """Все даты, какие удалось найти, с указанием источника каждой."""
    d = {}
    m = DATA_V_IMENI.search(os.path.basename(put))
    if m:
        god = m.group(3)
        god = god if len(god) == 4 else '20' + god
        try:
            d['имя файла'] = datetime.date(int(god), int(m.group(2)), int(m.group(1)))
        except ValueError:
            pass
    for pole, klyuch in (('created', 'создан'), ('modified', 'изменён')):
        mm = re.search(r'<dcterms:%s[^>]*>(\d{4})-(\d{2})-(\d{2})' % pole, core)
        if mm:
            d[klyuch] = datetime.date(int(mm.group(1)), int(mm.group(2)), int(mm.group(3)))
    mm = re.search(r'<cp:revision>(\d+)', core)
    if mm:
        d['правок'] = int(mm.group(1))
    try:
        d['файл на диске'] = datetime.date.fromtimestamp(os.path.getmtime(put))
    except OSError:
        pass
    return d


# Порядок доверия к датам. Дата в имени поставлена человеком и означает событие;
# дата правки внутри docx ставится Word и означает работу над файлом; дата
# файловой системы не означает ничего — её меняет копирование папки.
#
# Это не догадка: в корпусе ДО десять файлов имеют одну дату 21.04.2025,
# проставленную за два с половиной часа при массовом пересохранении, а «Работа
# с задачами» числится свежей только потому, что её конвертировали из старого
# формата. Содержание там от 2017 года.
DOVERIE = ['имя файла', 'изменён', 'создан', 'файл на диске']


def _chto_novee(a, b):
    """Что новее и по какому признаку. Возвращает (кто, признак, пояснение)."""
    for priznak in DOVERIE:
        da, db = a['daty'].get(priznak), b['daty'].get(priznak)
        if da is None or db is None or da == db:
            continue
        pozzhe = 'первый' if da > db else 'второй'
        return (pozzhe, priznak,
                'по признаку «%s»: %s против %s' % (priznak, da, db))
    ra, rb = a['daty'].get('правок'), b['daty'].get('правок')
    if ra is not None and rb is not None and ra != rb:
        return ('первый' if ra > rb else 'второй', 'правок',
                'даты совпали, различается число правок Word: %d против %d' % (ra, rb))
    return (None, None, 'даты не различают: все известные признаки совпали '
                        'или отсутствуют')


def _zagolovok(abzacy):
    """Первый содержательный абзац — он же обычно заголовок документа."""
    return abzacy[0] if abzacy else ''


def _slova(s):
    """Значащие слова: от трёх букв.

    Четырёх было мало. «А 3.3.3. Оперативное планирование и выполнение работ по
    ППП» и сосед «…по ПНР» отличаются ровно тремя буквами, и при пороге в четыре
    эти три буквы были невидимы: имена выглядели одинаковыми, и документ уходил
    в очередь оператора ни за что.
    """
    return set(re.findall(r'[а-яёa-z0-9]{3,}', s.lower()))


def _shozhest(a, b):
    """Общих слов к ОБЪЕДИНЕНИЮ, а не к меньшему набору.

    От меньшего считать нельзя, и это выяснилось на смешанной папке. Журнал
    «Обновление рабочей базы ERP 27.07.2026» начинается словами «Рабочая база
    1С ERP+PM НЕВАЛАБ 2021 обновлена…», а рядом лежит «Е 4. Транзит» — два
    значащих слова. Оба случайно нашлись в зачине, доля от меньшего вышла 100 %,
    и журнал уехал в очередь оператора как документ с чужим заголовком. Так
    уехали восемь журналов подряд.

    Симметричный счёт этого не допускает: короткое имя, полностью вошедшее в
    длинный текст, даёт малую долю от объединения — а именно длинный текст и
    есть признак того, что перед нами не заголовок.
    """
    sa, sb = _slova(a), _slova(b)
    if not sa or not sb:
        return 0.0
    return len(sa & sb) / float(len(sa | sb))


def chuzhoy_zagolovok(put, abzacy, sosedi=None):
    """Не стоит ли в начале документа заголовок ДРУГОГО файла этой папки.

    Признак узкий и потому надёжный. Первая версия проверки сверяла имя файла с
    первым абзацем и требовала сходства — и сразу поймала «Список изменений по
    учету серийных наборов», который просто начинается с текста, а не с
    заголовка. Имя там верное, документ верный, придираться не к чему.

    Настоящий случай выглядел иначе. Файл назван «А 2 Передача проекта в
    работу», а первая строка внутри — «С Процессы фин.результата и закрытия
    периода», и в той же папке лежит файл ровно с этим именем. Вот это и
    проверяется: похож ли зачин документа на имя СОСЕДА сильнее, чем на своё
    собственное.

    Почему это важнее обычного дубля. Дубль мы бы нашли и по совпадению текста,
    но выбрали бы более поздний по дате — то есть оставили бы документ под
    чужим именем. Бот назвал бы источником «Передачу проекта в работу», отвечая
    про закрытие периода, и проверка ответа этого не увидела бы: ответ верен сам
    по себе, неверна подпись под ним.
    """
    if not abzacy:
        return True, 'документ пуст — сверять нечего'
    # Заголовок — это ОДНА строка. Две строки давали лишний повод: во вторую
    # попадал обычный текст, и с ним случайно сходилось чужое имя.
    zachin = abzacy[0]
    # Заголовок короток. Абзац на полтораста знаков — это уже текст документа, а
    # не его название, и сверять с ним имена соседей бессмысленно.
    if len(zachin) > 150:
        return True, 'документ начинается текстом, а не заголовком — сверять нечего'
    svoyo = os.path.splitext(os.path.basename(put))[0]
    moya = _shozhest(svoyo, zachin)

    if sosedi is None:
        papka = os.path.dirname(os.path.abspath(put))
        try:
            sosedi = [f for f in os.listdir(papka)
                      if f.lower().endswith('.docx') and not f.startswith('~$')]
        except OSError:
            sosedi = []

    luchshiy, ego_dolya = None, 0.0
    for f in sosedi:
        if os.path.basename(f) == os.path.basename(put):
            continue
        d = _shozhest(os.path.splitext(os.path.basename(f))[0], zachin)
        if d > ego_dolya:
            luchshiy, ego_dolya = os.path.basename(f), d

    # Сосед должен выигрывать заметно, а не на волосок: имена документов одной
    # папки похожи друг на друга, и мелкий перевес ничего не значит. Порог 0,25
    # разницы выведен на разобранном случае — там было 1,00 против 0,25.
    # Условие «своё имя тоже подходит» стоит рядом с «сосед подходит лучше», и
    # без него проверка ловит пары почти одинаковых названий. В методике так
    # ушли в очередь «Инструкция по настройке АС НеваЛаб» и «…по первоначальной
    # настройке…»: зачин подходит обоим, и придираться не к чему — а что это
    # дубль, скажет сравнение текстов, для того оно и есть.
    if (luchshiy and ego_dolya >= 0.55 and moya < 0.4
            and ego_dolya - moya >= 0.25):
        return (False,
                'начало документа похоже на имя СОСЕДНЕГО файла «%s» (%.0f%%) '
                'сильнее, чем на своё собственное (%.0f%%). Первая строка: «%s»'
                % (luchshiy, 100 * ego_dolya, 100 * moya, abzacy[0][:90]))

    # Второй признак — «ни одно слово имени не встречается в тексте» — был
    # здесь и убран в тот же день. На методике он поднял «0 Глоссарий»,
    # «5. Проекты» и «Е 1. Ценообразование»: документ называется по разделу, а
    # внутри говорит по существу, не повторяя заголовка. Все три — нормальные
    # документы.
    #
    # Очередь оператора живёт ровно до тех пор, пока в ней нет мусора. Три
    # ложных повода из шести — и на неё перестают смотреть, а вместе с ними
    # перестают видеть настоящий. Лучше узкая проверка, ловящая один случай, чем
    # широкая, которую отключат.
    return True, 'зачин документа своему имени не противоречит'


def razobrat(put, sosedi=None):
    tekst, kartinki, core = _tekst(put)
    abzacy = _abzacy(tekst)
    sovpalo, poyasnenie = chuzhoy_zagolovok(put, abzacy, sosedi)
    return {
        'put': put,
        'imya': os.path.basename(put),
        'abzacy': abzacy,
        'znakov': len(re.sub(r'\s+', ' ', tekst)),
        'kartinok': len(kartinki),
        'hashi_kartinok': set(kartinki.values()),
        'daty': _daty(put, core),
        'imya_sootvetstvuet': sovpalo,
        'imya_poyasnenie': poyasnenie,
        'zagolovok': _zagolovok(abzacy),
    }


def sravnit(put_a, put_b, primerov=5):
    """Сравнить два документа. Возвращает словарь, годный и человеку, и коду."""
    a, b = razobrat(put_a), razobrat(put_b)
    sa, sb = set(a['abzacy']), set(b['abzacy'])
    obshchih = len(sa & sb)
    # Доля считается от МЕНЬШЕГО документа. От большего она всегда мала, и
    # «часть внутри целого» выглядела бы как «разные документы»: у «Списка
    # изменений» восемь общих абзацев — это 44 % короткого и 12 % длинного.
    znamenatel = min(len(sa), len(sb)) or 1
    dolya = obshchih / float(znamenatel)

    vyvod = POLOSY[-1][1]
    for porog, nazvanie in POLOSY:
        if dolya >= porog:
            vyvod = nazvanie
            break

    kto, priznak, pro_daty = _chto_novee(a, b)
    obshchih_kartinok = len(a['hashi_kartinok'] & b['hashi_kartinok'])

    trebuet_operatora = []
    for storona, d in (('первый', a), ('второй', b)):
        if not d['imya_sootvetstvuet']:
            trebuet_operatora.append('%s: %s' % (storona, d['imya_poyasnenie']))

    return {
        'pervyy': {k: v for k, v in a.items()
                   if k not in ('abzacy', 'hashi_kartinok')},
        'vtoroy': {k: v for k, v in b.items()
                   if k not in ('abzacy', 'hashi_kartinok')},
        'obshchih_abzacev': obshchih,
        'abzacev_pervyy': len(sa),
        'abzacev_vtoroy': len(sb),
        'dolya_obshchego': round(dolya, 3),
        'obshchih_kartinok': obshchih_kartinok,
        'vyvod': vyvod,
        'novee': kto,
        'priznak_novizny': priznak,
        'pro_daty': pro_daty,
        'tolko_v_pervom': sorted(sa - sb, key=len, reverse=True)[:primerov],
        'tolko_vo_vtorom': sorted(sb - sa, key=len, reverse=True)[:primerov],
        'trebuet_operatora': trebuet_operatora,
    }


def slovami(r):
    """Тот же ответ строками — для чтения человеком и для сообщения в телеграм."""
    s = []
    s.append('%s (доля общего %.0f%% от меньшего)'
             % (r['vyvod'], 100 * r['dolya_obshchego']))
    s.append('абзацев: %d и %d, общих %d; одинаковых картинок %d'
             % (r['abzacev_pervyy'], r['abzacev_vtoroy'],
                r['obshchih_abzacev'], r['obshchih_kartinok']))
    if r['novee']:
        s.append('новее %s — %s' % (r['novee'], r['pro_daty']))
    else:
        s.append(r['pro_daty'])
    for stroka in r['trebuet_operatora']:
        s.append('НУЖЕН ОПЕРАТОР — ' + stroka)
    return s
