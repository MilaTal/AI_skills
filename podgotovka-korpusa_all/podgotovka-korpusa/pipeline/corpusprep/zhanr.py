"""Согласен ли текст документа с жанром, который ему назначен папкой.

Решение владельца 20.09.2026: в базу идут только инструкции ERP и ДО. Всё
остальное — методика, журнал доработок, описание типового решения, таблица — не
ошибка разбора, а отказ в переносе с сообщением оператору.

**Жанр определяется папкой, а не текстом, и это не лень.** Папку выбирает
человек, и в ней нет догадки. Попытка определять жанр по содержанию замерена на
169 документах корпуса, и лучшее, что удалось выжать, — 88 % верных ответов:
пятнадцать настоящих инструкций отвергались бы зря, пять журналов проходили бы.

Почему так плохо. Журнал доработок, описывающий изменение в интерфейсе, читается
как инструкция: те же «нажать», «перейти», «заполнить». Плотность этих слов у
инструкций ERP — медиана 2,9 на тысячу знаков при четверти ниже 1,0; у журналов
медиана 0,0 при четверти выше 0,9. Полосы налезают, и никакой порог их не
разведёт. Отказывать документу на таком основании нельзя.

**Поэтому текст здесь не определяет жанр, а спорит с ним.** Проверка узкая и
односторонняя: она ловит один случай — когда документ, объявленный инструкцией,
начинается зачином журнала доработок. На 55 инструкциях корпуса этот зачин не
встретился ни разу, на 40 старых журналах — 38 раз. Сработала — значит документ
лежит не в той папке, и решать должен человек.

Это тот же выбор, что был сделан в проверке «чужой заголовок»: лучше узкая
проверка, ловящая один случай, чем широкая, которую отключат из-за ложных
срабатываний.
"""
import re

# Зачин журнала доработок. Формула устойчивая: «Рабочая база 1С "ERP+PM НЕВАЛАБ
# 2021" обновлена 14.05.2025, c текущим обновлением внесены изменения…».
# Допуски здесь на разнобой в написании, а не на смысл: между «базой» и
# «обновлена» помещается название базы в кавычках.
ZACHIN_ZHURNALA = re.compile(r"рабоч\w*\s+баз\w*.{0,120}?обновлен", re.I | re.S)

# Жанры, которые принимаются в базу. Список закрытый и живёт в коде: правило,
# которое обязано держаться всегда, в подсказке модели не держится.
PRINIMAEM = ('Инструкция',)
SISTEMY = ('ERP', 'DO')


def zhanr_prinimaetsya(document_type, system):
    """Принимается ли этот жанр в базу. Возвращает (да/нет, причина)."""
    zh = (document_type or '').strip()
    sis = (system or '').strip()
    if zh not in PRINIMAEM:
        return False, ('жанр «%s» в базу не принимается: берём только %s'
                       % (zh or 'не указан', ', '.join(PRINIMAEM)))
    if sis not in SISTEMY:
        return False, ('система «%s» не из списка: берём только %s'
                       % (sis or 'не указана', ', '.join(SISTEMY)))
    return True, 'жанр и система приняты'


def spor_s_tekstom(tekst, document_type):
    """Спорит ли текст с назначенным жанром. Возвращает (спорит, причина).

    Проверка односторонняя: ловит журнал, объявленный инструкцией, и не ловит
    обратного. Обратное и не нужно — журналы в базу не идут вовсе.
    """
    if (document_type or '').strip() not in PRINIMAEM:
        return False, 'жанр и так не принимается — спорить не о чем'
    nachalo = re.sub(r'\s+', ' ', tekst or '')[:600]
    m = ZACHIN_ZHURNALA.search(nachalo)
    if m:
        return True, ('документ объявлен инструкцией, но начинается зачином '
                      'журнала доработок: «%s»'
                      % re.sub(r'\s+', ' ', m.group(0))[:90])
    return False, 'текст жанру не противоречит'


def proverit(cfg, tekst_pervogo=None):
    """Проверка жанра для машинного отчёта.

    tekst_pervogo — текст любого одного документа партии, если он под рукой.
    Без него проверяется только жанр из конфига, и этого достаточно: главное
    правило владельца держится именно на нём.
    """
    zh = cfg.get('document_type')
    sis = cfg.get('system')
    prinyat, prichina = zhanr_prinimaetsya(zh, sis)
    itog = {
        'document_type': zh,
        'system': sis,
        'prinimaetsya': prinyat,
        'prichina': prichina,
        'spor_s_tekstom': False,
    }
    if prinyat and tekst_pervogo:
        sporit, pochemu = spor_s_tekstom(tekst_pervogo, zh)
        itog['spor_s_tekstom'] = sporit
        if sporit:
            itog['prinimaetsya'] = False
            itog['prichina'] = pochemu
    return itog
